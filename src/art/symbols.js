export const ART_KEYS = Object.keys(S);

export function symbolMarkup(key) {
  const fn = S[key];
  if (!fn) return '';
  return `<symbol id="sym-${key}" viewBox="0 0 512 512">`
    + `<g stroke="${OUT}" stroke-width="14" stroke-linejoin="round" stroke-linecap="round">${fn()}</g>`
    + '</symbol>';
}

// 종당 <symbol> 하나를 정의하고 <use> 로 참조한다 (기획서 12.7)
export function buildSpriteSheet() {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('id', 'sprite-sheet');
  svg.style.position = 'absolute';
  svg.style.width = '0';
  svg.style.height = '0';
  svg.style.overflow = 'hidden';
  svg.innerHTML = ART_KEYS.map(symbolMarkup).join('');
  return svg;
}

export function mountSpriteSheet(root = document.body) {
  if (document.getElementById('sprite-sheet')) return;
  root.prepend(buildSpriteSheet());
}

export function hasArt(key) {
  return Boolean(S[key]);
}
