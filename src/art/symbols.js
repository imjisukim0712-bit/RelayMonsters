// 몬스터 전신 벡터 아트 (기획서 12장)
//
// 규칙
//  · viewBox 0 0 512 512, 전신을 중앙 84% 안에 배치 (여백 8%)
//  · 외곽선 14 / 내부 디테일 8, 선 색 #2B2B3A
//  · 한 부위 안은 반드시 단색. 그라디언트·텍스처·드롭섀도 없음
//  · 머리·몸통·이동에 필요한 부위가 실루엣에서 모두 읽혀야 한다
//  · 기본 방향은 오른쪽(적을 향함). 링에서는 좌우 반전만 사용한다
//  · 카드 배경·테두리·초상화 크롭을 넣지 않는다 (투명 배경 전신)

const OUT = '#2B2B3A';
const NS = 'stroke="none"';

const E = (cx, cy, rx, ry, f, x = '') => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${f}" ${x}/>`;
const C = (cx, cy, r, f, x = '') => `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${f}" ${x}/>`;
const P = (d, f, x = '') => `<path d="${d}" fill="${f}" ${x}/>`;
const R = (x, y, w, h, r, f, ex = '') => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${r}" fill="${f}" ${ex}/>`;
// 굵은 외곽선이 있는 사지·꼬리·촉수: 어두운 밑선 + 색상 덧선
const band = (d, w, c) => `<path d="${d}" fill="none" stroke="${OUT}" stroke-width="${w + 14}" stroke-linecap="round" stroke-linejoin="round"/><path d="${d}" fill="none" stroke="${c}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"/>`;
const limb = (x1, y1, x2, y2, w, c) => band(`M${x1} ${y1}L${x2} ${y2}`, w, c);
const det = (d, c = OUT, w = 8) => `<path d="${d}" fill="none" stroke="${c}" stroke-width="${w}" stroke-linecap="round"/>`;
const eye = (cx, cy, r = 12) => C(cx, cy, r, OUT, NS);
const eyeW = (cx, cy, r = 20) => C(cx, cy, r, '#FFFFFF') + C(cx + 3, cy + 2, Math.round(r * 0.42), OUT, NS);
const angryEye = (cx, cy, r = 18) => C(cx, cy, r, '#FFF3C4') + C(cx + 2, cy, Math.round(r * 0.38), OUT, NS);

// 네 다리 (뒷다리 먼저 그리면 앞다리가 위에 온다)
const quadLegs = (y0, y1, xs, w, c) => xs.map((x) => limb(x, y0, x + (x > 256 ? 6 : -6), y1, w, c)).join('');
// 박쥐형 막날개 (dir: -1 왼쪽 / 1 오른쪽). 부호는 곱셈으로만 만든다 (문자열 "--" 방지)
const membraneWing = (cx, cy, dir, c) => {
  const d = dir;
  return P(`M${cx} ${cy} q${d * 70} -86 ${d * 140} -44 q${-d * 26} 30 ${-d * 6} 52`
    + ` q${d * 30} -6 ${d * 46} 16 q${-d * 34} 14 ${-d * 40} 40 q${-d * 54} -18 ${-d * 100} -64Z`, c);
};
// 깃털 날개
const featherWing = (cx, cy, dir, c) => {
  const d = dir;
  return P(`M${cx} ${cy} c${d * 30} -70 ${d * 96} -102 ${d * 140} -86`
    + ` c${d * 8} 34 ${-d * 18} 70 ${-d * 56} 92 c${d * 22} 4 ${d * 40} 16 ${d * 48} 34`
    + ` c${-d * 56} 16 ${-d * 108} -4 ${-d * 132} -40Z`, c);
};

